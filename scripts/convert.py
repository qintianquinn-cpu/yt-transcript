"""把 whisper 的繁体中文转写，转成简体中文书面语。

两步：
  1) OpenCC 繁 -> 简
  2) 粤语口语词 -> 书面语（whisper 会把粤语语音写成粤语用字，
     如「係」「嘅」「咗」，目标稿应统一成普通话书面表达）

用法: python3 convert.py transcript_mlx.json > transcript_simp.txt
"""

import json
import re
import sys

import opencc

# 粤语口语 -> 书面语。长的排前面，避免「唔使」被「唔」先切掉。
CANTONESE = [
    ("唔該", "麻烦"), ("唔使", "不用"), ("唔緊要", "不要紧"),
    ("而家", "现在"), ("呢排", "这阵子"), ("點解", "为什么"),
    ("做乜", "干什么"), ("咩事", "什么事"), ("諗清楚", "想清楚"),
    ("諗咗", "想了"), ("諗下", "想一下"), ("諗", "想"),
    ("而家", "现在"), ("聽日", "明天"), ("琴日", "昨天"),
    ("尋日", "昨天"), ("朝早", "早上"), ("晏晝", "下午"),
    ("夜晚", "晚上"), ("返工", "上班"), ("落雨", "下雨"),
    ("飲茶", "喝早茶"), ("食飯", "吃饭"), ("傾偈", "聊天"),
    ("搞掂", "搞定"), ("迫爆", "拼命"), ("夾硬", "硬要"),
    ("最緊要", "最重要"), ("起碼", "至少"), ("卒之", "总之"),
    ("同學仔", "同学"), ("女女", "女儿"), ("男仔", "男孩"),
    ("喺", "在"), ("係", "是"), ("嘅", "的"), ("咗", "了"),
    ("唔", "不"), ("睇", "看"), ("攞", "拿"), ("拎", "拿"),
    ("啲", "些"), ("吓", "吧"), ("嗰", "那"), ("嘢", "东西"),
    ("嚟", "来"), ("哋", "们"), ("佢", "他"), ("畀", "给"),
    ("嚿", "个"), ("冇", "没有"), ("攰", "累"), ("晒", "全部"),
    ("勁", "很"), ("掟", "扔"), ("嗱", "那"), ("嘞", "了"),
    ("嘅哋", "的"), ("吓", "吧"), ("㗎", "呢"),
]

cc = opencc.OpenCC("t2s")


def convert(text):
    t = cc.convert(text)
    for src, dst in CANTONESE:
        if src in t:
            t = t.replace(src, dst)
    # 修掉替换后可能出现的不自然叠字
    t = re.sub(r"在在", "在", t)
    t = re.sub(r"不不", "不", t)
    t = re.sub(r"了的", "的", t)
    t = re.sub(r"全部部", "全部", t)
    t = re.sub(r"现在在", "现在", t)
    t = re.sub(r"高高|大大|好好|年年", r"\g<0>", t)
    return t


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "transcript_mlx.json"
    data = json.load(open(path))
    segs = data.get("segments", [])
    for s in segs:
        m, sec = divmod(int(s["start"]), 60)
        print(f"[{m:02d}:{sec:02d}] {convert(s['text'])}")


if __name__ == "__main__":
    main()
